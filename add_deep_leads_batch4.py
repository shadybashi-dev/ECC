    existing_emails = set(lead['Email'].strip().lower() for lead in existing_leads)
    existing_entities = set(lead['Business_Name'].strip().lower() for lead in existing_leads)

    added_count = 0
    for lead in new_leads:
        em = lead['Email'].strip().lower()
        bn = lead['Business_Name'].strip().lower()
        if em in existing_emails:
            print(f"Skipping duplicate email: {em}")
            continue
        if bn in existing_entities:
            print(f"Skipping duplicate entity: {bn}")
            continue
        existing_leads.append(lead)
        existing_emails.add(em)
        existing_entities.add(bn)
        added_count += 1

    with open('/home/user/ECC/verified_leads.json', 'w', encoding='utf-8') as f:
        json.dump(existing_leads, f, ensure_ascii=False, indent=2)

    print(f"Successfully added {added_count} leads. Total records now: {len(existing_leads)}")
    print(f"Total unique emails now: {len(existing_emails)}")

