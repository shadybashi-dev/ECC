#!/usr/bin/env node
// Antonia's Pizza — route every "Order" button to the right Toast location (idempotent).
//   node examples/antonias-order-links.mjs <siteDir>
//
// Why: all ~100 order buttons pointed at https://antoniaspizza.toast.site/, whose landing page
// is a geolocation finder that often fails ("We couldn't locate you!" / "No results found").
// Every order started with an extra, sometimes broken, step.
//
// What it does:
//   1. Buttons that are clearly about one location (data-loc, "Order SLO", location pages,
//      the SLO/Paso tab panels) link straight to that location's Toast menu.
//   2. Every remaining generic button keeps the Toast root as its no-JS fallback. The injected
//      js/order-picker.js catches the click and asks "SLO or Paso?" once, then remembers.
//   3. UTM tags on every Toast link, so Toast/GA can see which page sent the order.
import fs from 'node:fs';
import path from 'node:path';

const SITE = path.resolve(process.argv[2] || '.');
const ROOT = 'https://antoniaspizza.toast.site/';
export const LOCS = {
  slo: 'https://antoniaspizza.toast.site/order/antonias-pizza-891-higuera-street',
  paso: 'https://antoniaspizza.toast.site/order/antonias-pizza-2-729-12th-street',
};
const PAGE_LOC = {
  'san-luis-obispo': 'slo', 'blog/late-night-slo': 'slo',
  'paso-robles': 'paso', 'blog/paso-wine-pairing': 'paso',
};
const PAGES = ['index', 'menu', 'san-luis-obispo', 'paso-robles', 'our-story', 'catering', 'order', 'faq',
  'privacy', 'deals', 'ajarski', '404', 'blog/index', 'blog/late-night-slo', 'blog/paso-wine-pairing'];
const FOLDER_COPY = new Set(['menu', 'san-luis-obispo', 'paso-robles', 'our-story', 'catering', 'order', 'faq',
  'privacy', 'deals', 'ajarski', 'blog/late-night-slo', 'blog/paso-wine-pairing']);

const utm = (page, loc) => `utm_source=antoniaspizza.com&utm_medium=website&utm_campaign=${loc || 'pick'}&utm_content=${encodeURIComponent(page.replace(/\//g, '-'))}`;
const TOAST_HREF = /href="https:\/\/antoniaspizza\.toast\.site\/(?:order\/[a-z0-9-]+)?(?:\?[^"]*)?"/;

function panelRanges(html) {
  // Byte ranges of the SLO / Paso tab panels on the home page.
  const out = [];
  for (const [id, loc] of [['loc-slo', 'slo'], ['loc-paso', 'paso']]) {
    const start = html.indexOf(`id="${id}"`);
    if (start < 0) continue;
    const next = html.indexOf('class="loc-panel', start + 10);
    const end = next > 0 ? next : html.indexOf('</section>', start);
    out.push({ start, end, loc });
  }
  return out;
}

function locationFor(tag, text, off, page, ranges) {
  const dl = tag.match(/\sdata-loc="(slo|paso)"/);
  if (dl) return dl[1];
  const t = text.replace(/<[^>]+>/g, ' ');
  const slo = /\bSLO\b|San Luis|Higuera/i.test(t);
  const paso = /\bPaso\b/i.test(t);
  if (slo !== paso) return slo ? 'slo' : 'paso';
  const r = ranges.find((x) => off > x.start && off < x.end);
  if (r) return r.loc;
  return PAGE_LOC[page] || null;
}

function rewrite(html, page) {
  const ranges = panelRanges(html);
  let n = { slo: 0, paso: 0, pick: 0 };
  html = html.replace(/<a\b[^>]*>([\s\S]*?)<\/a>/g, (whole, inner, off) => {
    const open = whole.match(/^<a\b[^>]*>/)[0];
    if (!TOAST_HREF.test(open)) return whole;
    const loc = locationFor(open, inner, off, page, ranges);
    const href = `${loc ? LOCS[loc] : ROOT}?${utm(page, loc)}`;
    let tag = open.replace(TOAST_HREF, `href="${href.replace(/&/g, '&amp;')}"`)
      .replace(/\sdata-order-pick(?==|\s|>)(="[^"]*")?/, '');
    if (!loc) tag = tag.replace(/^<a\b/, '<a data-order-pick');
    n[loc || 'pick']++;
    return tag + whole.slice(open.length);
  });
  // Load the picker once per page, after main.js.
  if (!html.includes('/js/order-picker.js')) {
    html = html.replace(/(\s*<\/body>)/, '\n  <script src="/js/order-picker.js" defer></script>$1');
  }
  return { html, n };
}

const PICKER_JS = `/* Order-location picker — generated by antonias-order-links.mjs.
   Generic "Order" buttons carry data-order-pick and point at the Toast root as a no-JS fallback.
   With JS we ask once which kitchen, remember it, and send the guest straight to that menu. */
(() => {
  "use strict";
  const LOCS = {
    slo:  { url: ${JSON.stringify(LOCS.slo)},  name: "San Luis Obispo", addr: "891 Higuera St", eta: "Pickup in about 15–20 min" },
    paso: { url: ${JSON.stringify(LOCS.paso)}, name: "Paso Robles",     addr: "729 12th St",    eta: "Pickup in about 25–30 min" }
  };
  const KEY = "ap-order-loc";
  const get = () => { try { return localStorage.getItem(KEY); } catch (_) { return null; } };
  const set = (v) => { try { localStorage.setItem(KEY, v); } catch (_) {} };
  const withQuery = (base, a) => base + (a.search || "");

  let dlg = null, lastLink = null;
  function build() {
    const css = document.createElement("style");
    css.textContent = \`
      .op-dialog{margin:auto;border:0;border-radius:28px;padding:0;max-width:min(440px,92vw);width:100%;background:var(--paper,#fffdf7);color:var(--navy,#0e3a52);box-shadow:0 30px 80px -20px rgba(14,58,82,.55)}
      .op-dialog::backdrop{background:rgba(14,58,82,.55);backdrop-filter:blur(3px)}
      .op-in{padding:1.6rem 1.5rem 1.3rem}
      .op-dialog h2{font-family:var(--font-display,inherit);font-size:1.5rem;line-height:1.15;text-transform:uppercase;margin:0 2.2rem .35rem 0}
      .op-dialog p{margin:0 0 1.1rem;opacity:.85;font-size:.95rem}
      .op-list{display:grid;gap:.75rem}
      .op-loc{display:flex;align-items:center;justify-content:space-between;gap:1rem;padding:1rem 1.15rem;border-radius:18px;border:2px solid var(--navy,#0e3a52);background:var(--sky,#bfe3f2);color:inherit;text-decoration:none;min-height:64px}
      .op-loc:hover,.op-loc:focus-visible{background:var(--sun,#ffd23f);outline:none}
      .op-loc:focus-visible{box-shadow:0 0 0 3px var(--paper,#fffdf7),0 0 0 6px var(--navy,#0e3a52)}
      .op-loc b{display:block;font-size:1.05rem;text-transform:uppercase;letter-spacing:.03em}
      .op-loc small{display:block;font-size:.82rem;opacity:.85}
      .op-loc .op-last[hidden]{display:none}.op-loc .op-last{display:inline-block;font-size:.7rem;font-weight:800;letter-spacing:.14em;text-transform:uppercase;background:var(--navy,#0e3a52);color:var(--paper,#fffdf7);border-radius:999px;padding:.2rem .55rem;margin-left:.4rem;vertical-align:2px}
      .op-arrow{font-size:1.4rem;line-height:1}
      .op-x{position:absolute;top:.9rem;right:.9rem;width:44px;height:44px;border-radius:50%;border:2px solid currentColor;background:transparent;color:inherit;font-size:1.3rem;cursor:pointer}
      .op-dialog .op-note{margin:.9rem 0 0;font-size:.78rem;opacity:.7}
      @media (prefers-reduced-motion:no-preference){.op-dialog[open]{animation:opIn .22s cubic-bezier(.22,1,.36,1)}}
      @keyframes opIn{from{opacity:0;transform:translateY(16px) scale(.97)}to{opacity:1;transform:none}}\`;
    document.head.appendChild(css);
    dlg = document.createElement("dialog");
    dlg.className = "op-dialog";
    dlg.setAttribute("aria-labelledby", "op-title");
    dlg.innerHTML =
      '<div class="op-in"><button type="button" class="op-x" aria-label="Close">×</button>' +
      '<h2 id="op-title">Which kitchen?</h2><p>Pick a location. We\\'ll open its Toast menu for pickup or delivery.</p>' +
      '<div class="op-list">' + Object.entries(LOCS).map(([k, l]) =>
        '<a class="op-loc" data-op-loc="' + k + '" href="' + l.url + '" target="_blank" rel="noopener">' +
        '<span><b>' + l.name + '<span class="op-last" hidden>Last time</span></b><small>' + l.addr + ' · ' + l.eta + '</small></span>' +
        '<span class="op-arrow" aria-hidden="true">→</span></a>').join("") +
      '</div><p class="op-note">We\\'ll remember your pick on this device.</p></div>';
    document.body.appendChild(dlg);
    dlg.querySelector(".op-x").addEventListener("click", () => dlg.close());
    dlg.addEventListener("click", (e) => { if (e.target === dlg) dlg.close(); });
    dlg.querySelectorAll("[data-op-loc]").forEach((a) => {
      a.addEventListener("click", () => {
        set(a.dataset.opLoc);
        if (lastLink) a.href = withQuery(LOCS[a.dataset.opLoc].url, lastLink).replace("utm_campaign=pick", "utm_campaign=" + a.dataset.opLoc);
        setTimeout(() => dlg.close(), 0);
      });
    });
    dlg.addEventListener("close", () => { if (lastLink && lastLink.focus) lastLink.focus({ preventScroll: true }); });
  }

  document.addEventListener("click", (e) => {
    const a = e.target.closest && e.target.closest("a[data-order-pick]");
    if (!a || e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    if (!window.HTMLDialogElement) return;              // very old browser: fall back to Toast's own finder
    lastLink = a;
    e.preventDefault();
    if (!dlg) build();
    const pref = get();
    dlg.querySelectorAll("[data-op-loc]").forEach((l) => { l.querySelector(".op-last").hidden = l.dataset.opLoc !== pref; });
    dlg.showModal();
    (dlg.querySelector('[data-op-loc="' + pref + '"]') || dlg.querySelector("[data-op-loc]")).focus();
  });
})();
`;

let totals = { slo: 0, paso: 0, pick: 0 };
for (const page of PAGES) {
  const f = path.join(SITE, `${page}.html`);
  if (!fs.existsSync(f)) continue;
  const { html, n } = rewrite(fs.readFileSync(f, 'utf8'), page);
  fs.writeFileSync(f, html);
  if (FOLDER_COPY.has(page) && fs.existsSync(path.join(SITE, page, 'index.html'))) fs.writeFileSync(path.join(SITE, page, 'index.html'), html);
  for (const k in n) totals[k] += n[k];
  console.log('•', page.padEnd(24), JSON.stringify(n));
}
fs.writeFileSync(path.join(SITE, 'js/order-picker.js'), PICKER_JS);

// main.js builds an "Order it" link at runtime (pizza picker wheel) — route it through the picker too.
const mainPath = path.join(SITE, 'js/main.js');
let main = fs.readFileSync(mainPath, 'utf8');
if (!main.includes('a.dataset.orderPick')) {
  main = main.replace('a.href = "https://antoniaspizza.toast.site/";', 'a.href = "https://antoniaspizza.toast.site/"; a.dataset.orderPick = "";');
  fs.writeFileSync(mainPath, main);
}
console.log(`done — direct SLO ${totals.slo}, direct Paso ${totals.paso}, via picker ${totals.pick}`);
